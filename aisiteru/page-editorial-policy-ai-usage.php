<h1>編集方針・AI利用ポリシー</h1>
<div class="priCon">
AISITERU.jp（AIシテル？）では、記事制作にあたり複数のAIを活用しています。<br>
本ページは、当サイトの編集方針およびAIの利用方法について、読者ならびに外部評価者に向けて明確に説明することを目的としています。<br>
<br>
本サイトのコンテンツは、特定の結論や価値観を押し付けるものではなく、<strong>複数の視点を提示することで、読者が自ら考えるための材料を提供すること</strong>を重視しています。

<h2>1. 編集方針について</h2>
AISITERU.jp の編集方針は、以下の考え方を基本としています。
<ul>
<li>特定の立場や結論を一方的に提示しない</li>
<li>明確な正解が存在しないテーマも積極的に扱う</li>
<li>情報を単純化せず、複数の視点を並べて提示する</li>
<li>読者の判断や思考を妨げない表現を心がける</li>
</ul>
そのため、本サイトでは、社会・時事・地域・歴史・倫理・仮説的テーマなど、見解が分かれやすい題材を多く取り上げています。

<h2>2. 複数のAIを比較する理由</h2>
一つのAIによる回答は、あくまで一つの視点に過ぎません。<br>
AISITERU.jp では、同一テーマに対して複数のAIに問いかけることで、
<ul>
<li>視点の違い</li>
<li>論理構成の差</li>
<li>前提や価値判断の傾向</li>
</ul>
といった要素を可視化します。<br>
これは、AIの優劣を決定することを目的としたものではなく、情報や思考の幅を把握するための比較として行っています。

<h2>3. AIの利用方法について</h2>
AISITERU.jp におけるAIの利用方法は、以下の通りです。
<ul>
<li>原則として、同一テーマ・同一趣旨のプロンプトを用いています</li>
<li>AIごとに意図的に質問内容を変えることは行っていません</li>
<li>記事全体の構成、比較軸、見出し設計は人間が行っています</li>
<li><strong>AIが生成した文章は、原則としてそのまま掲載しています</strong></li>
</ul>

同一テーマについては、原則として全てのAIに対し、同一の趣旨・条件のプロンプトを用いて問いかけています。<br>
これは、AIごとの思考や表現の違いを公平に比較するためです。<br>
<br>
AIごとの思考や表現の違いそのものに価値があると考えているため、<br>
誤字脱字、明らかな事実誤認、不適切な表現を除き、<strong>内容や論旨に手を加えることは行っていません</strong>。<br>
編集は、比較しやすさや可読性を確保するための体裁調整など、必要最低限に留めています。

<h2>4. 情報の正確性と利用に関する注意</h2>
AIが生成する情報には、事実誤認や不完全な内容が含まれる可能性があります。<br>
AISITERU.jp では、AIごとの思考や表現の違いそのものを比較対象とするため、重大な誤認や不適切な表現を除き、原則として生成結果をそのまま掲載しています。<br>
<br>
AISITERU.jp では、明らかな誤認や不適切な表現が確認された場合には、修正・補足を行うよう努めていますが、本サイトの内容は最終的な判断材料ではなく、参考情報としてご利用ください。<br>
<br>
特に、以下の分野についてはご注意ください。
<ul>
<li>医療</li>
<li>法律</li>
<li>投資・金融</li>
<li>その他、専門的判断を要する内容</li>
</ul>
これらについては、必ず専門家や公式情報をご確認ください。

<h2>5. 誘導・断定を行わない姿勢</h2>
AISITERU.jp は、以下の点を重視しています。
<ul>
<li>特定の結論への誘導を行わない</li>
<li>読者の価値判断を制限しない</li>
<li>感情的・扇動的な表現を避ける</li>
</ul>
複数の視点を提示した上で、「どのように考えるか」は読者自身に委ねる、という姿勢を大切にしています。

<h2>6. 記事内容の更新・修正について</h2>
本サイトの記事は、社会状況や技術の変化に応じて、内容の見直しや追記を行う場合があります。<br>
<br>
修正を行う際は、記事全体の趣旨や比較構造を損なわない形で反映します。


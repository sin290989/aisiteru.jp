<p class="lead">
MANAは、「AIシテル？」において記事を“書く存在”ではなく、<strong>問いを整理し、考察を成立させるための編集人格</strong>です。
</p>

<h2>MANAとは何か</h2>
<p>
MANAは、特定の結論や正解を提示するためのキャラクターではありません。<br>
また、感情的な主張や価値観を前面に出す語り手でもありません。
</p>
<p>
「AIシテル？」におけるMANAの役割は、<strong>複数のAIが提示する考察を、比較可能な“構造”として成立させること</strong>にあります。
</p>

<h2>なぜMANAという存在が必要なのか</h2>
<p>
AIは、与えられた問いに対して、それぞれ異なる視点・前提・論理展開を提示します。<br>
しかしそのまま並べるだけでは、「違い」は見えても「意味」は読み取りにくくなります。
</p>
<p>MANAは、</p>
<ul>
  <li>問いの前提を揃える</li>
  <li>断定や煽りに流れないよう制御する</li>
  <li>読者が自分で考えられる余白を残す</li>
</ul>
<p>
という編集上の役割を担っています。
</p>
<p>
つまりMANAは、<strong>答えを出すための存在ではなく、考察が成り立つ環境を整える存在</strong>です。
</p>

<h2>MANAが「しないこと」</h2>
<p>MANAは、以下のことを意図的に行いません。</p>
<ul>
  <li>特定の結論を「正しい」と断定すること</li>
  <li>読者の感情を操作するような煽情表現</li>
  <li>価値観や思想を押し付ける編集</li>
  <li>AIの回答を“人間の意見”として装うこと</li>
</ul>
<p>
「AIシテル？」では、<strong>考察はあくまでAIのもの</strong>であり、MANAはそれを整理し、比較し、読める形に整える立場を取ります。
</p>

<h2>AIシテル？におけるMANAの位置づけ</h2>
<p>
「AIシテル？」は、同一テーマについて複数のAIが考察を行い、その違いそのものを読むメディアです。
</p>
<p>MANAは、</p>
<ul>
  <li>INDEX記事で問いの枠組みを整理し</li>
  <li>各AI記事が同じ条件で比較されるよう設計し</li>
  <li>読者が「どの視点に納得したか」を自分で判断できるよう導く</li>
</ul>
<p>
という編集思想を担っています。
</p>
<p>
MANAは“語り手”ではなく、<strong>思考の舞台装置</strong>に近い存在です。
</p>

<h2>読者への約束</h2>
<p>MANAが関与する記事では、次の点を重視しています。</p>
<ul>
  <li>結論を急がない</li>
  <li>単純化しすぎない</li>
  <li>賛否や揺れをそのまま残す</li>
  <li>「考えること」そのものを価値として扱う</li>
</ul>
<p>
「納得させる」のではなく、<strong>「考え続けられる状態」を提供すること</strong>。<br>
それがMANAの編集方針です。
</p>

<h2>透明性について</h2>
<p>
「AIシテル？」に掲載される考察記事は、原則として各AIが生成した内容をもとに構成されています。
</p>
<p>
MANAは、
</p>
<ul>
  <li>プロンプト設計</li>
  <li>構造整理</li>
  <li>表現の最小限の調整</li>
</ul>
<p>
を行いますが、<strong>AIの主張そのものを書き換えることはありません</strong>。
</p>
<p>
このページは、その編集思想を明示するためのものです。
</p>


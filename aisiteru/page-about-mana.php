<p class="lead">
MANAは、「AIシテル？」において記事を<strong>書く主体</strong>ではなく、<strong>問いを整理し、考察が成立するための編集上の役割</strong>として位置づけられています。
</p>

<h2>MANAとは何か</h2>
<p>
MANAは、特定の結論や正解を提示するためのキャラクターではありません。<br>
また、感情的な主張や価値観を前面に出す語り手でもありません。
</p>
<p>
「AIシテル？」におけるMANAの役割は、<strong>複数のAIが提示する考察を、比較可能な“構造”として整理すること</strong>にあります。
</p>

<h2>なぜMANAという役割が必要なのか</h2>
<p>
AIは、与えられた問いに対して、それぞれ異なる視点・前提・論理展開を提示します。<br>
しかし、それらをそのまま並べるだけでは、「違い」は見えても「意味」は読み取りにくくなります。
</p>
<p>MANAは、編集上の配慮として、</p>
<ul>
  <li>問いの前提をできる限り揃えること</li>
  <li>断定や煽りに流れにくい構成を保つこと</li>
  <li>読者が自分で考えられる余白を残すこと</li>
</ul>
<p>
といった点を重視しています。
</p>
<p>
つまりMANAは、<strong>答えを導くための存在ではなく、考察が成立する環境を整えるための編集的な役割</strong>です。
</p>

<h2>MANAが意図していないこと</h2>
<p>MANAは、次のような行為を目的とはしていません。</p>
<ul>
  <li>特定の結論を「正しい」と断定すること</li>
  <li>読者の感情に訴えることを主目的とした表現</li>
  <li>価値観や思想を押し付ける編集</li>
  <li>AIの回答を人間の意見として扱うこと</li>
</ul>
<p>
「AIシテル？」では、<strong>考察はあくまでAIによるもの</strong>であり、MANAはそれらを整理し、比較し、読める形に整える立場を取っています。
</p>

<h2>AIシテル？におけるMANAの位置づけ</h2>
<p>
「AIシテル？」は、同一テーマについて複数のAIが考察を行い、その違いそのものを読み解くためのメディアです。
</p>
<p>MANAは、編集上の役割として、</p>
<ul>
  <li>INDEX記事で問いの枠組みを整理し</li>
  <li>各AI記事が同じ条件で比較されるよう設計し</li>
  <li>読者がどの視点に納得したかを自分で判断できるよう配慮する</li>
</ul>
<p>
といった点を意識しています。
</p>
<p>
MANAは“語り手”ではなく、<strong>思考のための構造を支える編集的な仕組み</strong>に近い存在です。
</p>

<h2>読者への姿勢</h2>
<p>MANAが関与する記事では、次の点を編集方針として重視しています。</p>
<ul>
  <li>結論を急がないこと</li>
  <li>単純化しすぎないこと</li>
  <li>賛否や揺れをそのまま残すこと</li>
  <li>「考える過程」そのものを価値として扱うこと</li>
</ul>
<p>
「納得させる」ことを目的とするのではなく、<strong>読者が考え続けられる状態を損なわないこと</strong>。<br>
それが「AIシテル？」におけるMANAの基本姿勢です。
</p>

<h2>透明性について</h2>
<p>
「AIシテル？」に掲載される考察記事は、原則として各AIが生成した内容をもとに構成されています。
</p>
<p>
MANAは編集上の工程として、
</p>
<ul>
  <li>プロンプト設計</li>
  <li>構造整理</li>
  <li>表現の最小限の調整</li>
</ul>
<p>
を行いますが、<strong>AIの主張そのものを書き換えることは行いません</strong>。
</p>
<p>
このページは、その編集方針と考え方を明示するためのものです。
</p>
